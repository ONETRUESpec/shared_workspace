#!/usr/bin/env node
// Bundles every data/*.json file into js/data.js so the planner works when opened
// directly from disk (file://) as well as from a web server. Run after editing data.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'data');
const out = {};
for (const file of readdirSync(dataDir).filter(f => f.endsWith('.json')).sort()) {
  const key = basename(file, '.json');
  try {
    out[key] = JSON.parse(readFileSync(join(dataDir, file), 'utf8'));
  } catch (err) {
    console.error(`data/${file}: invalid JSON (${err.message})`);
    process.exit(1);
  }
}
const banner = '// GENERATED by scripts/bundle-data.mjs from data/*.json. Do not edit by hand.\n';
const body = `window.OH_DATA = ${JSON.stringify(out)};\n`;
writeFileSync(join(root, 'js', 'data.js'), banner + body);
console.log(`bundled ${Object.keys(out).length} data files -> js/data.js (${(body.length / 1024).toFixed(1)} KiB)`);
